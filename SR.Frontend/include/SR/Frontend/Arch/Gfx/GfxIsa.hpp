enum class OperandKind : std::uint8_t
{
    None,
    Sgpr,
    Vgpr,
    Sdst,   // 7-bit scalar destination; may name EXEC/VCC
    Ssrc,   // 8-bit scalar source; may be an inline constant or literal
    Src,    // 9-bit vector source; may be an inline constant or literal
    Vsrc,   // 8-bit VGPR source
    Literal,
    Simm16,
    Imm32,
    Label,
    Vcc,
    Exec,
    // Memory operand layouts. The decoder normalises these to Sdst/Sgpr/Vgpr/
    // Imm32 so the lifter sees one consistent operand order.
    SmemSdst,
    SmemSbase,
    SmemOffset,
    SmemOffset24,
    SmemSoffset,
    FlatVdst,
    FlatVaddr,
    FlatSaddr,
    FlatData,
    FlatOffset12,
    FlatOffset13,
    GlobalVdst,
    GlobalVaddr,
    GlobalVsrc,
    GlobalIoffset,
    Vop1Sdst,
    Vop3Sdst,
    DsAddr,   // DS ADDR: VGPR holding the byte offset
    DsData0,  // DS DATA0: VGPR data source or load destination
    DsData1,  // DS DATA1: second VGPR operand for the 2-address forms
    DsDest,   // DS VDST: VGPR destination of the _RTN forms
    BufferVdst,
    BufferVaddr,
    BufferVsrc,
    BufferSoffset,
    BufferIoffset,
};

struct Operand
{
    OperandKind kind = OperandKind::None;
    std::uint32_t value = 0;
    bool isInline = false; // value is an inline-constant index, not a register
};

struct DecodedInstruction
{
    Op op = Op::Invalid;
    Encoding encoding = Encoding::Sop1;
    Arch arch = Arch::Gfx10;
    std::uint16_t opcode = 0;  // ISA opcode within the encoding
    std::uint32_t pc = 0;       // byte offset in the code object
    std::uint32_t wordCount = 0;
    std::uint32_t word0 = 0;
    std::uint32_t word1 = 0;

    // VOP3 modifiers, kept for diagnostics and lowering.
    std::uint8_t abs = 0;
    std::uint8_t neg = 0;
    std::uint8_t omod = 0;
    bool clamp = false;
    bool execMask = false; // V_CMPX updates EXEC in addition to VCC
    std::uint8_t opSel = 0;    // VOP3P source-half selectors
    std::uint8_t opSelHi = 0;  // VOP3P high selector bits
    std::uint8_t negHi = 0;    // VOP3P high-half negate bits

    std::uint32_t dsOffset0 = 0; // DS immediate byte offset
    std::uint32_t dsOffset1 = 0; // DS second immediate offset for the 2-address forms
    bool dsGds = false;
    bool bufferOffen = false;
    bool bufferIdxen = false;
    bool bufferTfe = false;
    std::uint8_t bufferFormat = 0;

    std::array<Operand, 6> operands{};
    std::uint8_t operandCount = 0;
};

